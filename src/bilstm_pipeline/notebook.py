"""Notebook facade. / Interface para notebooks."""

from .execution import load_run, run

_COMPONENT_DEMO_FILENAME = "component_demo.json"
_EVALUATION_FILENAME = "evaluation.json"


def _component_run(run_id: str) -> dict:
    """Load a run with component artifacts. / Carrega execução com artefatos dos componentes."""
    result = load_run(run_id)
    if result["legacy"] or not (result["directory"] / _COMPONENT_DEMO_FILENAME).is_file():
        raise ValueError("This run has no component demonstration artifacts; create a new synthetic run.")
    return result


def show_parameters(run_id: str) -> None:
    """Display effective parameters. / Exibe parâmetros efetivos."""
    from IPython.display import display
    result = load_run(run_id)
    print(f"Run: {run_id}")
    display(result["config"])


def show_results(run_id: str) -> None:
    """Display a completed demonstration. / Exibe demonstração concluída."""
    from IPython.display import Image, display
    import pandas as pd
    result = load_run(run_id)
    print(result["manifest"].get("origem") if result["legacy"] else result["manifest"]["origin"])
    directory = result["directory"]
    data = "dados_sinteticos.csv" if result["legacy"] else "synthetic_data.csv"
    image = "figuras/demonstracao.png" if result["legacy"] else "figures/demo.png"
    display(pd.read_csv(directory / data))
    display(Image(filename=str(directory / image)))
    if not result["legacy"] and (directory / "evaluation" / _EVALUATION_FILENAME).exists():
        import json
        evaluation = json.loads((directory / "evaluation" / _EVALUATION_FILENAME).read_text(encoding="utf-8"))
        print("Synthetic classification example — not scientific results")
        display(pd.DataFrame(evaluation["metrics"]["classes"]).T)
        display(Image(filename=str(directory / "figures" / "confusion_matrix.png")))
        display(Image(filename=str(directory / "figures" / "binary_metrics.png")))


def show_metrics(run_id: str) -> None:
    """Display synthetic metrics. / Exibe métricas sintéticas."""
    import json
    import pandas as pd
    from IPython.display import Image, display
    result = _component_run(run_id)
    directory = result["directory"]
    evaluation = json.loads((directory / "evaluation" / _EVALUATION_FILENAME).read_text(encoding="utf-8"))
    components = json.loads((directory / _COMPONENT_DEMO_FILENAME).read_text(encoding="utf-8"))
    print("Synthetic data only — not scientific findings.")
    display(pd.DataFrame(evaluation["metrics"]["classes"]).T)
    display(pd.DataFrame([evaluation["metrics"]], columns=["total", "accuracy", "specificity", "false_positive_rate", "f1_macro", "f1_weighted"]))
    display(pd.DataFrame([components["accuracy_interval"]]))
    display(Image(filename=str(directory / "figures" / "confusion_matrix.png")))
    display(Image(filename=str(directory / "figures" / "binary_metrics.png")))


def show_robustness(run_id: str) -> None:
    """Display synthetic paired comparisons. / Exibe comparações pareadas sintéticas."""
    import json
    import pandas as pd
    from IPython.display import Image, display
    result = _component_run(run_id)
    directory = result["directory"]
    components = json.loads((directory / _COMPONENT_DEMO_FILENAME).read_text(encoding="utf-8"))
    rows = []
    for name, data in components["perturbations"].items():
        interval = data["paired_accuracy_difference"]
        rows.append({"condition": name, "accuracy": data["metrics"]["accuracy"], "difference": interval["estimate"], "lower": interval["lower"], "upper": interval["upper"], "valid_resamples": interval["valid_resamples"], "skipped_resamples": interval["skipped_resamples"]})
    print("Synthetic data only — confidence intervals use grouped paired resampling.")
    display(pd.DataFrame(rows))
    display(components["perturbation_parameters"])
    figure = directory / "figures" / "robustness.png"
    if figure.is_file():
        display(Image(filename=str(figure)))
    else:
        print("The robustness chart was not generated by this older run.")


